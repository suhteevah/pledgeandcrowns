//! Render Pledge & Crown ASCII-grid sprite refs to PNG. Pure Rust;
//! palette + every `design/art/refs/ref-*.jsx` are baked into the
//! binary at build time via `build.rs` + `include_str!`. At runtime
//! this binary parses the embedded sources, looks up palette codes,
//! and writes PNG-32 with transparent background to
//! `<repo>/design/art/refs/png/REF<NN>.png`.
//!
//! ## Why this exists
//!
//! The old pipeline went `.jsx` → React+Babel-standalone in a browser →
//! canvas dataURL → JSON snapshot → Python decoder → PNG. Four moving
//! parts, three of them temptations to fall back to side-renderers
//! when one fails (the 2026-05-02 art-lead batch 3 hit exactly that
//! failure mode). This binary collapses the chain to one Rust process
//! with zero network/browser dependency. Per Matt's no-fallbacks rule.
//!
//! ## Invocation
//!
//! ```text
//! cargo run -p render-refs --release
//! ```
//!
//! Run from the workspace root, or set `RENDER_REFS_OUT=<dir>` to
//! redirect PNG output. By default writes to `<workspace>/design/art/refs/png/`.
#![forbid(unsafe_code)]

use std::collections::HashMap;
use std::path::PathBuf;

use anyhow::{Context, Result, anyhow, bail};
use image::{ImageBuffer, Rgba, RgbaImage};
use regex::Regex;
use tracing_subscriber::EnvFilter;

/// Palette source baked at compile time. `include_str!` makes this a
/// `&'static str` literal — no fs read, no path resolution at runtime.
const PALETTE_SRC: &str = include_str!("../../../design/art/palette.js");

// Generated by build.rs — `pub static REF_FILES: &[(&str, &str)] = ...;`
// where each pair is `(jsx_filename, file_contents_baked_at_build_time)`.
include!(concat!(env!("OUT_DIR"), "/ref_table.rs"));

fn main() -> Result<()> {
    tracing_subscriber::fmt()
        .with_env_filter(
            EnvFilter::try_from_default_env()
                .unwrap_or_else(|_| EnvFilter::new("render_refs=info")),
        )
        .init();

    let palette = Palette::parse(PALETTE_SRC).context("parsing baked palette source")?;
    tracing::info!("palette: {} entries", palette.count());

    let out_dir = resolve_out_dir()?;
    std::fs::create_dir_all(&out_dir).with_context(|| format!("creating {}", out_dir.display()))?;

    // Render everything in memory first so a malformed ref fails the run
    // before any PNG on disk is touched.
    let outcome = render_all(REF_FILES, &palette)?;
    if !outcome.failures.is_empty() {
        for (name, reason) in &outcome.failures {
            tracing::error!("failed to render {name}: {reason}");
        }
        let list = outcome
            .failures
            .iter()
            .map(|(name, reason)| format!("  {name}: {reason}"))
            .collect::<Vec<_>>()
            .join("\n");
        bail!(
            "{} ref(s) failed to render and are not in SKIP_ALLOWED:\n{list}",
            outcome.failures.len()
        );
    }

    for (png_name, img) in &outcome.rendered {
        let dst = out_dir.join(png_name);
        img.save(&dst)
            .with_context(|| format!("writing {}", dst.display()))?;
        tracing::debug!("wrote {}", dst.display());
    }
    tracing::info!(
        "done — {} refs rendered ({} allow-listed skips) to {}",
        outcome.rendered.len(),
        outcome.skipped.len(),
        out_dir.display()
    );
    Ok(())
}

/// Legacy refs that compose their pixels in JS (no literal grid the Rust
/// renderer can read). These, and only these, may fail to render. Any
/// other `ref-*.jsx` that fails is a hard error. `artboard-frame.jsx` and
/// `palette-legend.jsx` are not `ref-*` so build.rs never embeds them.
const SKIP_ALLOWED: &[&str] = &[
    "ref-04-tiles-village.jsx",
    "ref-05-tiles-tower.jsx",
    "ref-06-editor.jsx",
    "ref-09-worldmap.jsx",
    "ref-09-worldmap-v2.jsx",
    "ref-10-title.jsx",
];

/// Result of rendering a set of refs: successes keyed by PNG name,
/// allow-listed skips, and unexpected failures (`(jsx_name, reason)`).
#[derive(Debug, Default)]
struct RenderOutcome {
    rendered: Vec<(String, RgbaImage)>,
    skipped: Vec<String>,
    failures: Vec<(String, String)>,
}

/// Render every `(jsx_name, source)` pair, sorting each into rendered,
/// allow-listed skip, or failure. Only a bad filename is an `Err` here —
/// per-ref render errors are collected so the caller can report them all.
fn render_all(files: &[(&str, &str)], palette: &Palette) -> Result<RenderOutcome> {
    let mut outcome = RenderOutcome::default();
    for (name, src) in files {
        let png_name = png_name_for(name)?;
        match render_ref(src, palette) {
            Ok(img) => {
                if SKIP_ALLOWED.contains(name) {
                    tracing::warn!(
                        "{name} is in SKIP_ALLOWED but rendered fine; remove it from the list"
                    );
                }
                tracing::info!(
                    "rendered {name} -> {png_name} ({}x{})",
                    img.width(),
                    img.height()
                );
                outcome.rendered.push((png_name, img));
            }
            Err(e) if SKIP_ALLOWED.contains(name) => {
                tracing::debug!("skipping allow-listed {name}: {e:#}");
                outcome.skipped.push((*name).to_owned());
            }
            Err(e) => outcome
                .failures
                .push(((*name).to_owned(), format!("{e:#}"))),
        }
    }
    Ok(outcome)
}

/// Dispatch one ref source to the right renderer. Tile sheets
/// (`const REF<NN>_TILES = { name: [...], ... };`) pack into an atlas;
/// everything else is a single literal grid.
fn render_ref(src: &str, palette: &Palette) -> Result<RgbaImage> {
    if src.contains("_TILES = {") {
        render_tiles(src, palette).context("tile sheet")
    } else {
        render_grid(src, palette)
    }
}

/// Resolve the PNG output directory. `RENDER_REFS_OUT` env wins; else
/// walk upward looking for the workspace marker (Cargo.toml + tools/render-refs)
/// and use `<workspace>/design/art/refs/png/`.
fn resolve_out_dir() -> Result<PathBuf> {
    if let Ok(p) = std::env::var("RENDER_REFS_OUT") {
        return Ok(PathBuf::from(p));
    }
    let mut dir = std::env::current_dir()?;
    loop {
        if dir.join("Cargo.toml").is_file() && dir.join("tools").join("render-refs").is_dir() {
            return Ok(dir.join("design").join("art").join("refs").join("png"));
        }
        if !dir.pop() {
            bail!(
                "could not locate workspace root from current directory; set RENDER_REFS_OUT to specify"
            );
        }
    }
}

/// Map a `.jsx` filename to its expected PNG filename. The `.jsx` files
/// follow `ref-<NN>-<slug>.jsx`; the PNG output is `REF<NN>.png` to
/// match the existing committed artifacts. Variant suffixes (`-v2`)
/// preserve the historical `REF09v2.png` naming.
fn png_name_for(jsx_name: &str) -> Result<String> {
    let stem = jsx_name
        .strip_prefix("ref-")
        .and_then(|s| s.strip_suffix(".jsx"))
        .ok_or_else(|| anyhow!("not a ref-*.jsx file: {jsx_name}"))?;
    let mut parts = stem.splitn(2, '-');
    let num = parts
        .next()
        .ok_or_else(|| anyhow!("missing NN in {jsx_name}"))?;
    if num.len() != 2 || !num.chars().all(|c| c.is_ascii_digit()) {
        bail!("expected 2-digit NN in {jsx_name}, got {num}");
    }
    let suffix = parts
        .next()
        .and_then(|slug| slug.rsplit_once("-v").map(|(_, v)| format!("v{v}")))
        .unwrap_or_default();
    Ok(format!("REF{num}{suffix}.png"))
}

#[derive(Debug)]
struct Palette {
    by_char: HashMap<char, Option<[u8; 4]>>,
}

impl Palette {
    fn parse(src: &str) -> Result<Self> {
        let mut by_char = HashMap::new();

        // Lines like:
        //   K: { hex: '#1B0810', name: 'Inkblood',       group: 'burgundy' },
        //   '!': { hex: '#E63946', name: 'Alarm scarlet', group: 'alarm' },
        //   '.': null,
        //   ' ': null,
        let entry_re = Regex::new(
            r"(?m)^\s*(?P<key>'[^']'|[A-Za-z>])\s*:\s*(?:null|\{\s*hex:\s*'(?P<hex>#[0-9A-Fa-f]{6})')",
        )?;

        for caps in entry_re.captures_iter(src) {
            let key_raw = &caps["key"];
            let ch = parse_palette_key(key_raw)
                .ok_or_else(|| anyhow!("unparseable palette key: {key_raw}"))?;
            let rgba = caps
                .name("hex")
                .map(|m| parse_hex_rgba(m.as_str()))
                .transpose()?;
            by_char.insert(ch, rgba);
        }

        // The palette source uses `'.': null,` and `' ': null,` for
        // transparency — make sure they landed even if the regex
        // missed an unusual key form.
        by_char.entry('.').or_insert(None);
        by_char.entry(' ').or_insert(None);

        if by_char.len() < 3 {
            bail!(
                "parsed only {} palette entries — looks broken",
                by_char.len()
            );
        }
        Ok(Self { by_char })
    }

    fn lookup(&self, c: char) -> Result<Option<[u8; 4]>> {
        self.by_char
            .get(&c)
            .copied()
            .ok_or_else(|| anyhow!("palette has no entry for char '{c}'"))
    }

    fn count(&self) -> usize {
        self.by_char.len()
    }
}

fn parse_palette_key(raw: &str) -> Option<char> {
    if raw.len() == 1 {
        raw.chars().next()
    } else if raw.len() == 3 && raw.starts_with('\'') && raw.ends_with('\'') {
        raw.chars().nth(1)
    } else {
        None
    }
}

fn parse_hex_rgba(hex: &str) -> Result<[u8; 4]> {
    let hex = hex.trim_start_matches('#');
    if hex.len() != 6 {
        bail!("hex color must be 6 chars, got `{hex}`");
    }
    let r = u8::from_str_radix(&hex[0..2], 16)?;
    let g = u8::from_str_radix(&hex[2..4], 16)?;
    let b = u8::from_str_radix(&hex[4..6], 16)?;
    Ok([r, g, b, 0xFF])
}

/// Parse a `.jsx` source string and render its grid to an RgbaImage.
/// Returns Err for refs that don't carry a `const REF<NN>_GRID = [...]`
/// (scaffolding / layout components). The `palette` lookup turns each
/// row character into a pixel; transparent codes (`.`, ` `) leave the
/// pixel at the buffer's RGBA(0,0,0,0) initial value.
fn render_grid(jsx_src: &str, palette: &Palette) -> Result<RgbaImage> {
    let grid_re = Regex::new(r"(?s)const\s+REF\d+(?:_V\d+)?_GRID\s*=\s*\[(?P<body>.*?)\]\s*;")?;
    let caps = grid_re
        .captures(jsx_src)
        .ok_or_else(|| anyhow!("no GRID literal found"))?;
    let body = &caps["body"];

    let line_re = Regex::new(r"'([^']*)'")?;
    let rows: Vec<&str> = line_re
        .captures_iter(body)
        .filter_map(|c| c.get(1).map(|m| m.as_str()))
        .collect();

    if rows.is_empty() {
        bail!("empty grid");
    }
    let width = rows[0].chars().count() as u32;
    let height = rows.len() as u32;
    if let Some((y, bad)) = rows
        .iter()
        .enumerate()
        .find(|(_, r)| r.chars().count() as u32 != width)
    {
        bail!(
            "irregular row widths (expected {width}): row {y} is {} wide",
            bad.chars().count()
        );
    }

    let mut img: RgbaImage = ImageBuffer::from_pixel(width, height, Rgba([0, 0, 0, 0]));
    for (y, row) in rows.iter().enumerate() {
        for (x, ch) in row.chars().enumerate() {
            if let Some(rgba) = palette.lookup(ch)? {
                img.put_pixel(x as u32, y as u32, Rgba(rgba));
            }
        }
    }
    Ok(img)
}

/// Parse a tile-sheet `.jsx` and pack its tiles row-major into one atlas.
///
/// The source carries `const REF<NN>_TILES = { name: ['row', ...], ... };`
/// plus `const REF<NN>_COLS = <n>;`. Every tile must share one size. Atlas
/// index = declaration order, so the game's tile constants follow the file.
/// Unlike scaffolding refs, a malformed tile sheet is a hard error naming
/// the offending tile — silent skips here would ship a shifted atlas.
fn render_tiles(jsx_src: &str, palette: &Palette) -> Result<RgbaImage> {
    let tiles_re = Regex::new(r"(?s)const\s+REF\d+_TILES\s*=\s*\{(?P<body>.*?)\}\s*;")?;
    let body = &tiles_re
        .captures(jsx_src)
        .ok_or_else(|| anyhow!("no TILES literal found"))?["body"];
    let cols_re = Regex::new(r"const\s+REF\d+_COLS\s*=\s*(?P<n>\d+)\s*;")?;
    let cols: u32 = cols_re
        .captures(jsx_src)
        .ok_or_else(|| anyhow!("tile sheet has no `const REF<NN>_COLS = <n>;`"))?["n"]
        .parse()?;
    if cols == 0 {
        bail!("REF<NN>_COLS must be at least 1");
    }

    let tile_re = Regex::new(r"(?s)(?P<name>[A-Za-z_][A-Za-z0-9_]*)\s*:\s*\[(?P<rows>.*?)\]")?;
    let line_re = Regex::new(r"'([^']*)'")?;
    let mut tiles: Vec<(&str, Vec<&str>)> = Vec::new();
    for caps in tile_re.captures_iter(body) {
        let name = caps.name("name").map_or("", |m| m.as_str());
        let rows_src = caps.name("rows").map_or("", |m| m.as_str());
        let rows: Vec<&str> = line_re
            .captures_iter(rows_src)
            .filter_map(|c| c.get(1).map(|m| m.as_str()))
            .collect();
        tiles.push((name, rows));
    }
    let (first_name, first_rows) = tiles.first().ok_or_else(|| anyhow!("empty tile sheet"))?;
    let th = first_rows.len() as u32;
    let tw = first_rows
        .first()
        .ok_or_else(|| anyhow!("tile `{first_name}` has no rows"))?
        .chars()
        .count() as u32;

    let sheet_rows = (tiles.len() as u32).div_ceil(cols);
    let mut img: RgbaImage =
        ImageBuffer::from_pixel(cols * tw, sheet_rows * th, Rgba([0, 0, 0, 0]));
    for (i, (name, rows)) in tiles.iter().enumerate() {
        if rows.len() as u32 != th {
            bail!("tile `{name}` has {} rows, expected {th}", rows.len());
        }
        let ox = (i as u32 % cols) * tw;
        let oy = (i as u32 / cols) * th;
        for (y, row) in rows.iter().enumerate() {
            let w = row.chars().count() as u32;
            if w != tw {
                bail!("tile `{name}` row {y} is {w} wide, expected {tw}");
            }
            for (x, ch) in row.chars().enumerate() {
                if let Some(rgba) = palette
                    .lookup(ch)
                    .with_context(|| format!("tile `{name}` row {y}"))?
                {
                    img.put_pixel(ox + x as u32, oy + y as u32, Rgba(rgba));
                }
            }
        }
    }
    tracing::debug!(
        "packed {} tiles ({tw}x{th}) into {cols}-column atlas",
        tiles.len()
    );
    Ok(img)
}

