//   up:    up_0,   up_1,          up_2,   up_1
//   left:  left_0, left_1,        left_2, left_1
//   right: the left frames flipped at runtime.
// up_1 and left_1 also serve as the standing poses facing away and sideways.
// Seen from behind the staff swaps to the frame-left side, as it must.
